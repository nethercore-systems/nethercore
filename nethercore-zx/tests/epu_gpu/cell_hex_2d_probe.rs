#[test]
fn cell_hex_2d_full_falsifier() {
    let p = probe_image(
        &format!(
            "{}\n{}\n{}",
            P,
            include_str!("fixtures/cell-hex-2d/evaluator.wgsl"),
            include_str!("fixtures/cell-hex-2d/full.wgsl")
        ),
        24,
        216,
    );
    assert!(p.iter().flatten().all(|x| x.is_finite()));
    let mut failures = 0;
    let mut nonzero = 0;
    for (i, r) in p.as_chunks::<24>().0.iter().enumerate() {
        let phase = i / 54;
        let i = i % 54;
        let fill = (i / 9) % 3;
        let byte = i % 3;
        let gap = i / 27;
        let jump = (0..3)
            .map(|c| (r[7][c] - r[10][c]).abs())
            .fold(0f32, f32::max);
        println!(
            "FULL phase={phase} row={i} byte_index={byte} fill_index={fill} gap_index={gap} pair={:?}/{:?} on={:?} owners={:?}/{:?} jump={jump}",
            r[7], r[10], r[13], r[6], r[9]
        );
        for point in 0..8 {
            assert_eq!(r[point * 3 + 1][3], 1., "packing/integral parity");
        }
        if fill == 0 && byte != 2 {
            for (a, b) in [(1, 4), (7, 10), (16, 19), (7, 13), (10, 13)] {
                for c in 0..3 {
                    assert!(
                        (r[a][c] - r[b][c]).abs() <= 0.01,
                        "all-filled bilateral/on-cut"
                    );
                }
            }
        }
        if fill == 1 && byte != 2 && gap == 0 && jump > 0.01 {
            println!("FALSIFIER_RAW {r:?}");
        }
        if fill == 1 && byte != 2 && gap == 0 && jump > 0.01 {
            failures += 1;
        }
        if byte != 2 && r[22][2] > 0.5 {
            nonzero += 1;
        }
    }
    assert!(
        failures > 0,
        "expected unchanged single-owner fill composition falsifier"
    );
    println!(
        "MIXED_FILL_CONTRACT_FALSIFIED witnesses={failures}; nonzero_floor_rows={nonzero}; no production adoption"
    );
}
